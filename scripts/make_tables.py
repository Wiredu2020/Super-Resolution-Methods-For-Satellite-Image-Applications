def table_natural():
    df = pd.read_csv(os.path.join(RESULTS, "results_summary.csv"))
    df["m"] = df.model.map(SHORT)
    datasets = ["Set5", "Set14", "BSD100", "Urban100", "DIV2K-val"]

    lines = [
        "% generated by scripts/make_tables.py -- do not edit by hand",
        "\\begin{table}[!ht]",
        "  \\centering",
        "  \\caption{Reconstruction accuracy on the natural-image benchmarks, "
        "reported as PSNR (dB) / SSIM on the luminance channel. Best result in "
        "each column in bold. ESRGAN is available only at $\\times 4$. "
        "Urban100 and DIV2K images are centre-cropped to a maximum side of 512 "
        "pixels, identically for every model.}",
        "  \\label{tab:natural}",
        "  \\small",
        "  \\begin{tabular}{@{}l" + "c" * len(datasets) + "@{}}",
        "    \\toprule",
        "    Method & " + " & ".join(datasets) + " \\\\",
        "    \\midrule",
    ]

    for scale in (2, 4):
        sub = df[df.scale == scale]
        lines.append(f"    \\multicolumn{{{len(datasets)+1}}}{{@{{}}l@{{}}}}"
                     f"{{\\emph{{Scale $\\times {scale}$}}}} \\\\")
        best = {d: sub[sub.dataset == d].psnr_db.max() for d in datasets}
        best_s = {d: sub[sub.dataset == d].ssim.max() for d in datasets}
        for m in ["Bicubic", "Lanczos", "FSRCNN", "ESPCN", "ESRGAN",
                  "LSMAN (proposed)"]:
            rows = sub[sub.m == m]
            if rows.empty:
                continue
            cells = []
            for d in datasets:
                r = rows[rows.dataset == d]
                if r.empty:
                    cells.append("--")
                    continue
                p, s = float(r.psnr_db.iloc[0]), float(r.ssim.iloc[0])
                cells.append(bold_if(f"{p:.2f}", np.isclose(p, best[d])) + " / " +
                             bold_if(f"{s:.4f}", np.isclose(s, best_s[d])))
            lines.append(f"    {m} & " + " & ".join(cells) + " \\\\")
        lines.append("    \\addlinespace")

    lines[-1] = "    \\bottomrule"
    lines += ["  \\end{tabular}", "\\end{table}", ""]
    write("tab_natural.tex", "\n".join(lines))


