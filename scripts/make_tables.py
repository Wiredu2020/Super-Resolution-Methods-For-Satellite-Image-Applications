def table_smallobjects():
    df = pd.read_csv(os.path.join(RESULTS, "results_smallobjects.csv"))
    bands = ["small", "medium", "large"]
    wide = df.pivot_table(index="condition", columns="band", values="accuracy")
    counts = df.drop_duplicates("band").set_index("band").n_test

    cuts_path = os.path.join(RESULTS, "smallobject_band_cuts.npy")
    if os.path.exists(cuts_path):
        c1, c2 = np.load(cuts_path)
        span = (f"Size groups are terciles of the object-size distribution: "
                f"below {c1:.0f}~px, {c1:.0f} to {c2:.0f}~px, and above "
                f"{c2:.0f}~px on the longest side in the high-resolution "
                f"reference. ")
    else:
        span = ""

    lines = [
        "% generated by scripts/make_tables.py -- do not edit by hand",
        "\\begin{table}[tbp]",
        "  \\centering",
        "  \\caption{Object recognition accuracy (\\%) on NWPU VHR-10, grouped "
        "by object size. " + span +
        "Whole images are degraded and reconstructed before the annotated "
        "objects are cropped, so objects are corrupted as they would be in a "
        "real acquisition. Best result among the reconstructions in each "
        "column in bold.}",
        "  \\label{tab:smallobjects}",
        "  \\begin{tabular}{@{}lcccc@{}}",
        "    \\toprule",
        "    & \\multicolumn{3}{c}{By object size} & \\\\",
        "    \\cmidrule(lr){2-4}",
        "    Classifier input & small & medium & large & all \\\\",
        "    \\midrule",
    ]

    sub = wide.drop(index="HR reference", errors="ignore")
    best = {b: sub[b].max() for b in bands if b in sub}
    all_col = df[df.band == "all"].set_index("condition").accuracy
    best_all = all_col.drop(index="HR reference", errors="ignore").max()

    for cond in CONDITIONS:
        if cond not in wide.index:
            continue
        if cond == "HR reference":
            lines.append("    \\midrule")
        cells = []
        for b in bands:
            v = wide.loc[cond, b] if b in wide.columns else np.nan
            s = "--" if np.isnan(v) else f"{v*100:.2f}"
            if not np.isnan(v) and b in best and np.isclose(v, best[b]):
                s = f"\\textbf{{{s}}}"
            cells.append(s)
        a = all_col.get(cond, np.nan)
        s = "--" if np.isnan(a) else f"{a*100:.2f}"
        if not np.isnan(a) and np.isclose(a, best_all):
            s = f"\\textbf{{{s}}}"
        cells.append(s)
        lines.append("    " + pretty(cond) + " & " + " & ".join(cells) + " \\\\")

    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    write("tab_smallobjects.tex", "\n".join(lines))
    print("     objects per band:",
          {b: int(counts.get(b, 0)) for b in bands})


