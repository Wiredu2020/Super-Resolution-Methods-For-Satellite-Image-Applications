def table_agriculture():
    df = pd.read_csv(os.path.join(RESULTS, "results_agriculture.csv"))

    def fmt(r, best):
        cells = []
        for col, spec in (("boundary_f1", "{:.3f}"), ("parcel_iou", "{:.3f}"),
                          ("canopy_f1", "{:.3f}")):
            s = spec.format(r[col])
            if col in best and np.isclose(r[col], best[col]):
                s = f"\\textbf{{{s}}}"
            cells.append(s)
        err = f"{r.count_error*100:.1f}"
        if "count_error" in best and np.isclose(r.count_error, best["count_error"]):
            err = f"\\textbf{{{err}}}"
        cells.append(err)
        return " & ".join(cells)

    sub = df[df.condition != "HR reference"]
    best = {c: sub[c].max() for c in ("boundary_f1", "parcel_iou", "canopy_f1")}
    best["count_error"] = sub.count_error.min()

    lines = [
        "% generated by scripts/make_tables.py -- do not edit by hand",
        "\\begin{table}[tbp]",
        "  \\centering",
        "  \\caption{Agricultural parcel delineation and canopy counting on the "
        f"{int(df.n_tiles.iloc[0])} satellite tiles. The reference is derived "
        "from the high-resolution image by the same fixed procedure applied to "
        "every condition, so the measure is agreement with full-resolution "
        "extraction rather than accuracy against field survey. Best result "
        "among the reconstructions in bold.}",
        "  \\label{tab:agriculture}",
        "  \\small",
        "  \\begin{tabular}{@{}lcccc@{}}",
        "    \\toprule",
        "    & \\multicolumn{2}{c}{Parcel delineation} "
        "& \\multicolumn{2}{c}{Canopy counting} \\\\",
        "    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        "    Input & Boundary F1 & Parcel IoU & Match F1 & Count error (\\%) \\\\",
        "    \\midrule",
    ]
    for cond in CONDITIONS:
        r = df[df.condition == cond]
        if r.empty:
            continue
        if cond == "HR reference":
            lines.append("    \\midrule")
        lines.append("    " + pretty(cond) + " & " + fmt(r.iloc[0], best) + " \\\\")
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    write("tab_agriculture.tex", "\n".join(lines))


