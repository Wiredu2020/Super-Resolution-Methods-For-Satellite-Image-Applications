def table_satellite():
    df = pd.read_csv(os.path.join(RESULTS, "results_satellite.csv"))
    order = ["Bicubic", "Lanczos", "FSRCNN", "ESPCN", "LSMAN (proposed)"]

    lines = [
        "% generated by scripts/make_tables.py -- do not edit by hand",
        "\\begin{table}[!ht]",
        "  \\centering",
        "  \\caption{Reconstruction accuracy on 21 satellite tiles, reported as "
        "mean $\\pm$ standard deviation over the set. Metrics are computed on "
        "the luminance channel with a border of $s$ pixels shaved. Best result "
        "in each column in bold.}",
        "  \\label{tab:satellite}",
        "  \\small",
        "  \\begin{tabular}{@{}lcccc@{}}",
        "    \\toprule",
        "    & \\multicolumn{2}{c}{Scale $\\times 2$} "
        "& \\multicolumn{2}{c}{Scale $\\times 4$} \\\\",
        "    \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        "    Method & PSNR (dB) & SSIM & PSNR (dB) & SSIM \\\\",
        "    \\midrule",
    ]

    best = {(s, k): df[df.scale == s][k].max() for s in (2, 4)
            for k in ("psnr_db", "ssim")}

    for m in order:
        cells = []
        for s in (2, 4):
            r = df[(df.scale == s) & (df.model == m)]
            if r.empty:
                cells += ["--", "--"]
                continue
            p, ps = float(r.psnr_db.iloc[0]), float(r.psnr_std.iloc[0])
            v, vs = float(r.ssim.iloc[0]), float(r.ssim_std.iloc[0])
            cells.append(bold_if(f"{p:.2f} $\\pm$ {ps:.2f}",
                                 np.isclose(p, best[(s, 'psnr_db')])))
            cells.append(bold_if(f"{v:.4f} $\\pm$ {vs:.4f}",
                                 np.isclose(v, best[(s, 'ssim')])))
        lines.append(f"    {m} & " + " & ".join(cells) + " \\\\")

    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    write("tab_satellite.tex", "\n".join(lines))


