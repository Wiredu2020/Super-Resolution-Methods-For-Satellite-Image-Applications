def wilson(p, n, z=1.96):
    """Wilson score interval -- reliable for proportions near 0 or 1, unlike
    the normal approximation."""
    d = 1 + z ** 2 / n
    centre = (p + z ** 2 / (2 * n)) / d
    half = z * np.sqrt(p * (1 - p) / n + z ** 2 / (4 * n ** 2)) / d
    return centre - half, centre + half


CONDITIONS = ["Native LR x2", "Bicubic x2", "LSMAN x2",
              "Native LR x4", "Bicubic x4", "LSMAN x4", "HR reference"]


def pretty(cond):
    """Condition name as it should appear in a table."""
    if cond == "HR reference":
        return "HR reference \\emph{(upper bound)}"
    kind, tag = cond.rsplit(" ", 1)
    if kind == "LSMAN":
        kind = "\\textbf{LSMAN}"
    return f"{kind} $\\times {tag.lstrip('x')}$"


def condition_rows(df, fmt, bold_best=None):
    """Emit one LaTeX row per condition, with a rule before the HR row."""
    lines = []
    best = {}
    if bold_best:
        sub = df[df.condition != "HR reference"]
        for col in bold_best:
            best[col] = sub[col].max()
    for cond in CONDITIONS:
        r = df[df.condition == cond]
        if r.empty:
            continue
        if cond == "HR reference":
            lines.append("    \\midrule")
        lines.append("    " + pretty(cond) + " & " + fmt(r.iloc[0], best) + " \\\\")
    return lines


def table_downstream():
    df = pd.read_csv(os.path.join(RESULTS, "results_downstream.csv"))
    n_test = int(df.n_test.iloc[0])

    def fmt(r, best):
        acc = f"{r.accuracy*100:.2f}"
        if "accuracy" in best and np.isclose(r.accuracy, best["accuracy"]):
            acc = f"\\textbf{{{acc}}}"
        return (f"{acc} & [{r.ci_lo*100:.1f}, {r.ci_hi*100:.1f}] "
                f"& {r.macro_f1:.3f}")

    lines = [
        "% generated by scripts/make_tables.py -- do not edit by hand",
        "\\begin{table}[tbp]",
        "  \\centering",
        "  \\caption{Land-use classification accuracy on UC Merced. The feature "
        "extractor and the linear classifier are identical across conditions, "
        f"and the test set holds {n_test} images. Intervals are $95\\%$ Wilson "
        "score intervals. Best result among the reconstructions in bold.}",
        "  \\label{tab:downstream}",
        "  \\begin{tabular}{@{}lccc@{}}",
        "    \\toprule",
        "    Classifier input & Accuracy (\\%) & $95\\%$ interval & Macro-F1 \\\\",
        "    \\midrule",
    ]
    lines += condition_rows(df, fmt, bold_best=["accuracy"])
    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    write("tab_downstream.tex", "\n".join(lines))
    for _, r in df.iterrows():
        print(f"     {r.condition:<14} {r.accuracy*100:.2f}%")


def _table_downstream_legacy():
    df = pd.read_csv(os.path.join(RESULTS, "results_downstream.csv"))
    base = float(df[df.variant == "Bicubic"].accuracy.iloc[0])
    n_test = int(df.n_test.iloc[0])

    lines = [
        "% generated by scripts/make_tables.py -- do not edit by hand",
        "\\begin{table}[tbp]",
        "  \\centering",
        "  \\caption{Land-use classification accuracy on UC Merced when the "
        "classifier is given each reconstruction of the same $\\times 4$ "
        "decimated input. The feature extractor and the linear classifier are "
        f"identical across rows, and the test set holds {n_test} images. "
        "Intervals are $95\\%$ Wilson score intervals. The three reconstructions "
        "overlap one another substantially and are not distinguishable at this "
        "sample size; only the high-resolution reference is separated from "
        "them.}",
        "  \\label{tab:downstream}",
        "  \\begin{tabular}{@{}lccc@{}}",
        "    \\toprule",
        "    Classifier input & Accuracy (\\%) & $95\\%$ interval "
        "& vs.\\ bicubic (pp) \\\\",
        "    \\midrule",
    ]
    for v in ["Native LR", "Bicubic", "LSMAN", "HR reference"]:
        r = df[df.variant == v]
        if r.empty:
            continue
        a = float(r.accuracy.iloc[0])
        lo, hi = wilson(a, n_test)
        name = {"LSMAN": "LSMAN (proposed)",
                "HR reference": "HR reference \\emph{(upper bound)}"}.get(v, v)
        d_s = "--" if v == "Bicubic" else f"${(a - base) * 100:+.2f}$"
        lines.append(f"    {name} & {a*100:.2f} & "
                     f"[{lo*100:.1f}, {hi*100:.1f}] & {d_s} \\\\")

    lines += ["    \\bottomrule", "  \\end{tabular}", "\\end{table}", ""]
    write("tab_downstream.tex", "\n".join(lines))

    for v in ["Bicubic", "LSMAN", "HR reference"]:
        a = float(df[df.variant == v].accuracy.iloc[0])
        lo, hi = wilson(a, n_test)
        print(f"     {v:<14} {a*100:.2f}%  [{lo*100:.1f}, {hi*100:.1f}]")


