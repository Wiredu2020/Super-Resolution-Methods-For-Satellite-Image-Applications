"""Emit the LaTeX result tables straight from the result CSVs.

Writing these by hand is how numbers drift between the data and the text, so
chapter 5 \\input{}s the files this script produces instead.
"""

import os

import numpy as np
import pandas as pd

THESIS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(THESIS, "results")
TEX = os.path.join(THESIS, "Bright_Wiredu_Nuakoh_Thesis_2023-24", "tables")
os.makedirs(TEX, exist_ok=True)

SHORT = {
    "Bicubic (classical)": "Bicubic",
    "Lanczos (classical)": "Lanczos",
    "FSRCNN (pretrained, SRCNN lineage)": "FSRCNN",
    "ESPCN (pretrained, SRCNN lineage)": "ESPCN",
    "ESRGAN (pretrained, x4 only)": "ESRGAN",
    "LSMAN (proposed)": "LSMAN (proposed)",
}


def write(name, body):
    path = os.path.join(TEX, name)
    with open(path, "w") as f:
        f.write(body)
    print("  wrote tables/" + name)


def bold_if(text, cond):
    return f"\\textbf{{{text}}}" if cond else text


